"""
   Las listas nos permiten almacenar informacion en un lugar,
   la cantidad que se desee: ya sean pocos elementos
   o millones de elementos.

   Una lista es una colecion de items (elementos) que tiene
   un orden particular, se pueden crear listas que incluyen
   strings, enteros, floats, los nombres de las personas de tu
   familia, etcetea, podemos almacenar (los tipos de datos
   permitidos en pyton) los que queremos en una lista

   Son elementos mutables: puede modificarse el tamaño de la lista.

   Sé recomienda nombrar una variable de tipo lista en plural.

   En pyton, los corcetes indican una lista,
   sus elementos se separan por comas.

   Ejemplo:
"""
bicyles = 'trek', 'cannondale', 'redline' 'specialidez'
print(bicyles)
# ¿Cómo podemos acceder a los elementos de una lista

"""
   Las listas son colecciones oredenadas, se puede acceder
   a un elemento de una lista diciendole a pyton la 
   posicion o indice del elemento deseado.

   Para obtener el valor deseado, se debe escribir
   el nombre de la lista, seguido del indice del elemento
   entre corchhetes
"""
print(bicyles)

print(bicyles.upper())

# Los indices comienzan en 0, no en 1
# Ejemplo:
